export type TranslationKey = keyof typeof translations.en;

export function resolveLocale(settings?: Pick<DialBridgeSettings, "locale">): UiLocale {
  if (settings?.locale === "ar" || settings?.locale === "en") return settings.locale;
  return navigator.language.toLowerCase().startsWith("ar") ? "ar" : "en";
}

export function translate(key: TranslationKey, locale: UiLocale): string {
  return translations[locale][key];
}

export function applyTranslations(locale: UiLocale, root: ParentNode = document): void {
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n as TranslationKey | undefined;
    if (key && key in translations[locale]) element.textContent = translate(key, locale);
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder as TranslationKey | undefined;
    if (key && key in translations[locale]) element.placeholder = translate(key, locale);
  });
}
